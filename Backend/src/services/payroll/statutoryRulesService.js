// Backend/src/services/payroll/statutoryRulesService.js
import pool from "../../config/database.js";

/**
 * Indian Statutory Rules Service
 * Handles deterministic computation for:
 * - Employees' Provident Fund (EPF/EPS/EDLI)
 * - Employees' State Insurance Corporation (ESIC)
 * - Professional Tax (Maharashtra & Slabs)
 * - Income Tax TDS (Section 192 under New Tax Regime)
 *
 * STATUTORY SOURCES & EFFECTIVE DATES (Last verified: 2026-10-28)
 * ──────────────────────────────────────────────────────────────────────────
 * EPF  : Employees' Provident Funds & Miscellaneous Provisions Act, 1952
 *        EPFO Circular — statutory wage ceiling ₹15,000 (w.e.f. 2014-09-01)
 *        Admin charges: EPFO Circular HQ/ACC/13(1)/2022/CIR/4 (w.e.f. 2022-06-01): 0.50%
 *        EDLI: Employees' Deposit-Linked Insurance Scheme, 1976: 0.50% (max ₹75 lakh cover)
 *
 * ESIC : Employees' State Insurance Act, 1948
 *        ESI Corporation — eligibility threshold ₹21,000/month (w.e.f. 2017-01-01)
 *        Employee rate 0.75% + Employer rate 3.25% (w.e.f. 2019-07-01 via ESI Notification)
 *
 * PT   : Maharashtra State Tax on Professions, Trades, Callings and Employments Act, 1975
 *        Schedule I: ₹0 (≤7,500), ₹175 (7,501–10,000), ₹200 (>10,000 standard months),
 *        ₹300 (February, to round annual total to ₹2,500)
 *        Female employees earning ≤₹25,000/month: Exempted per Maharashtra Govt notification
 *        (Government Gazette, Extraordinary, Part IV-B, dated 1 April 2023)
 *
 * TDS  : Income Tax Act, 1961 — Section 192 (salary withholding)
 *        Finance Act 2026 (FY 2026–27 / AY 2027–28) — New Tax Regime (Section 115BAC)
 *        Standard Deduction ₹75,000 (Finance Act 2024, w.e.f. AY 2025-26 onwards)
 *        Section 87A rebate — tax liability nil if taxable income ≤ ₹7,00,000
 *        Health & Education Cess — 4% on income tax
 *
 * COMPLIANCE NOTICE: Internal reports generated by this service are NOT filed returns.
 * Actual statutory filings must be submitted on official EPFO/ESIC/income tax portals.
 * Rates marked [UNVERIFIED] require compliance review before use in production payroll.
 * ──────────────────────────────────────────────────────────────────────────
 */
class StatutoryRulesService {
  /**
   * Fetch active statutory config by code from database.
   * The DB config is the authoritative source for rates when present.
   * Calculation methods fall back to hardcoded FY 2026-27 constants when DB is unavailable.
   */
  async getConfig(statutoryCode) {
    try {
      const res = await pool.query(
        `SELECT config_version, rules_json, effective_from 
         FROM payroll_statutory_configs 
         WHERE statutory_code = $1 AND is_active = TRUE 
         ORDER BY effective_from DESC LIMIT 1`,
        [statutoryCode]
      );
      if (res.rows.length > 0) {
        return res.rows[0];
      }
    } catch (err) {
      console.warn(`Could not load DB config for ${statutoryCode}:`, err.message);
    }
    return null;
  }

  /**
   * EPF Calculation
   *
   * Legal ceiling modes:
   *   '15000'  — Statutory EPF wage ceiling (EPFO Act, ₹15,000 w.e.f. 2014-09-01).
   *              Employee PF contribution capped at ₹1,800/mo.
   *              THIS IS THE ONLY LEGALLY MANDATED CEILING.
   *
   *   'ACTUAL' — Full basic wage used without any ceiling.
   *              This is Voluntary Provident Fund (VPF) — the employee OPTS IN voluntarily.
   *              Permitted under EPF Act Section 6 proviso; employer contribution is
   *              still capped at 12% of ₹15,000 wage for EPF purposes (employer is NOT
   *              obliged to match VPF above the statutory ceiling unless agreed separately).
   *              ⚠️  When pfCeilingMode = 'ACTUAL', employer share in this engine also
   *              uses the actual wage for simplicity; adjust the employer cap if your CTC
   *              policy limits employer VPF matching.
   *
   *   '25000'  — ⚠️  NOT a legal EPF statutory ceiling.
   *              ₹25,000 has been discussed in proposed EPFO amendments but as of
   *              2026-10-28 no gazette notification has raised the statutory ceiling.
   *              Using this mode is treated here as VPF (similar to 'ACTUAL') and is
   *              flagged [COMPLIANCE_REVIEW_REQUIRED].
   *              Do NOT represent this to employees as a government-mandated threshold.
   *
   * Employer contribution split (EPFO statutory):
   *   EPS  : 8.33% — ALWAYS capped at ₹15,000 wage (EPS-95, unchanged)
   *   EPF  : Employer 12% total − EPS (≥0, clamped)
   *   EDLI : 0.50% on EPS wage (Employees' Deposit-Linked Insurance Scheme, 1976)
   *   Admin: 0.50% on PF wage (EPFO admin charges, w.e.f. 2022-06-01)
   *
   * @param {number} basicPay - Prorated basic pay for the month
   * @param {string|boolean} pfCeilingMode - '15000' | 'ACTUAL' | '25000'
   * @returns {Object} EPF breakdown
   */
  calculateEPF(basicPay, pfCeilingMode = "15000") {
    const basic = Math.max(0, Number(basicPay) || 0);

    let wageCeiling;
    let complianceFlag = null;

    if (pfCeilingMode === true || pfCeilingMode === "ACTUAL" || pfCeilingMode === "FULL") {
      wageCeiling = basic; // VPF — no ceiling
    } else if (pfCeilingMode === "25000" || pfCeilingMode === 25000) {
      // ⚠️ Not a current legal ceiling — treat as VPF with a soft cap of ₹25,000
      wageCeiling = 25000;
      complianceFlag =
        "[COMPLIANCE_REVIEW_REQUIRED] ₹25,000 PF ceiling mode is NOT a legal EPF statutory ceiling as of 2026-10-28. " +
        "Treat as VPF. Verify with your EPFO compliance officer before use.";
    } else {
      wageCeiling = 15000; // Statutory default (EPFO Act, w.e.f. 2014-09-01)
    }

    const pfWage = Math.min(basic, wageCeiling);

    // Employee Share: 12% of PF wage (rounded to nearest rupee)
    const employeePF = Math.round(pfWage * 0.12);

    // Employer Share
    // EPS wage is ALWAYS capped at ₹15,000 (EPS-95, never changed by EPFO)
    const epsWage = Math.min(basic, 15000);
    const employerEPS = Math.round(epsWage * 0.0833);

    // Employer EPF = employer 12% total − EPS; clamped to ≥0 to prevent negative values
    // (rounding can theoretically make employerEPS > employerTotal at low wages)
    const employerTotal12Pct = Math.round(pfWage * 0.12);
    const employerEPF = Math.max(0, employerTotal12Pct - employerEPS);

    const employerEDLI = Math.round(epsWage * 0.005);
    const employerAdmin = Math.round(pfWage * 0.005);

    const totalEmployerPF = employerEPS + employerEPF + employerEDLI + employerAdmin;

    return {
      pfWage,
      wageCeiling,
      pfCeilingMode,
      employeePF,
      employerEPS,
      employerEPF,
      employerEDLI,
      employerAdmin,
      totalEmployerPF,
      isCapped: wageCeiling !== basic && basic > wageCeiling,
      complianceFlag,
    };
  }

  /**
   * ESIC Calculation
   *
   * Source: Employees' State Insurance Act, 1948
   *         ESI Corporation notification w.e.f. 2019-07-01
   * Threshold: Gross monthly wage ≤ ₹21,000 (w.e.f. 2017-01-01)
   * Employee contribution: 0.75% of Gross (rounded to nearest rupee)
   * Employer contribution: 3.25% of Gross (rounded to nearest rupee)
   *
   * FIX (2026-10-28): Both employee and employer contributions now use Math.round
   * for consistency. Previously employee used Math.ceil which broke the 4% total.
   * The statutory rounding rule is "nearest rupee" for both contributions per ESIC
   * circular guidelines.
   *
   * @param {number} grossPay - Monthly gross pay
   */
  calculateESIC(grossPay) {
    const gross = Math.max(0, Number(grossPay) || 0);
    const threshold = 21000;

    if (gross > threshold) {
      return {
        eligible: false,
        gross,
        threshold,
        employeeESIC: 0,
        employerESIC: 0,
        totalESIC: 0,
      };
    }

    // Both use Math.round — symmetric rounding per ESIC circular
    const employeeESIC = Math.round(gross * 0.0075);
    const employerESIC = Math.round(gross * 0.0325);

    return {
      eligible: true,
      gross,
      threshold,
      employeeESIC,
      employerESIC,
      totalESIC: employeeESIC + employerESIC,
    };
  }

  /**
   * Maharashtra Professional Tax (PT)
   *
   * Source: Maharashtra State Tax on Professions, Trades, Callings and Employments Act, 1975
   *         Schedule I (as amended, verified 2026-10-28)
   *
   * Slabs (monthly gross):
   *   ≤ ₹7,500          → ₹0
   *   ₹7,501 – ₹10,000  → ₹175
   *   > ₹10,000          → ₹200 (standard months)
   *   > ₹10,000 (Feb)    → ₹300 (to reach annual ₹2,500 cap: 11×₹200 + 1×₹300 = ₹2,500)
   *
   * Female exemption:
   *   Maharashtra Govt notification: Female employees with gross ≤ ₹25,000/month are exempt.
   *   Source: Maharashtra Govt Gazette, Extraordinary, Part IV-B, dated 1 April 2023.
   *   ⚠️  This exemption has been contested — verify current status with local compliance officer.
   *
   * @param {number} grossPay
   * @param {string} gender - 'Male' | 'Female' (case-insensitive prefix check)
   * @param {number} month  - 1-12 (February = 2 triggers surcharge)
   */
  calculateProfessionalTax(grossPay, gender = "Male", month = 1) {
    const gross = Math.max(0, Number(grossPay) || 0);
    const isFemale = String(gender).toLowerCase().startsWith("f");

    if (isFemale && gross <= 25000) {
      return {
        ptAmount: 0,
        slab: "Female Exemption (≤ ₹25,000) — Maharashtra Gazette Apr 2023",
      };
    }

    if (gross <= 7500) {
      return { ptAmount: 0, slab: "Nil (≤ ₹7,500)" };
    }

    if (gross <= 10000) {
      return { ptAmount: 175, slab: "₹7,501 – ₹10,000" };
    }

    // February surcharge: ₹300 instead of ₹200 (annual total = 11×200 + 1×300 = ₹2,500)
    const ptAmount = Number(month) === 2 ? 300 : 200;
    return {
      ptAmount,
      slab: Number(month) === 2 ? "> ₹10,000 (February surcharge ₹300)" : "> ₹10,000 (Standard ₹200)",
    };
  }

  /**
   * Income Tax Withholding (TDS under Section 192)
   *
   * Source: Income Tax Act, 1961 — Section 192 (salary withholding)
   *         Finance Act 2026 (FY 2026–27 / AY 2027–28)
   *         New Tax Regime — Section 115BAC (default from AY 2024-25 onwards)
   *
   * Standard Deduction: ₹75,000 (Finance Act 2024, w.e.f. AY 2025-26)
   *
   * New Regime Slabs (FY 2026-27 / AY 2027-28):
   *   ₹0           – ₹3,00,000  →  0%
   *   ₹3,00,001    – ₹7,00,000  →  5%
   *   ₹7,00,001    – ₹10,00,000 → 10%
   *   ₹10,00,001   – ₹12,00,000 → 15%
   *   ₹12,00,001   – ₹15,00,000 → 20%
   *   Above ₹15,00,000           → 30%
   *
   * Section 87A Rebate: Total tax = ₹0 if taxable income ≤ ₹7,00,000 (after standard deduction)
   * Health & Education Cess: 4% on income tax liability
   *
   * NOTE ON YTD: This method computes the ANNUAL TAX from the annualEstimatedIncome
   * and divides by 12 for monthly TDS. For a proper YTD-aware TDS (where remaining tax
   * is spread over remaining months of FY), the caller should pass
   * (annualTax - ytdDeducted) / remainingMonths. The engine currently uses 1/12
   * division as a simplification. Full YTD-aware TDS is a planned enhancement.
   *
   * @param {number} annualEstimatedIncome - Estimated annual gross income
   * @param {string} regime - 'New' | 'Old' (only 'New' supported; 'Old' falls back to 'New')
   */
  calculateTDS(annualEstimatedIncome, regime = "New") {
    const grossAnnual = Math.max(0, Number(annualEstimatedIncome) || 0);
    const standardDeduction = 75000;
    const taxableIncome = Math.max(0, grossAnnual - standardDeduction);

    // Section 87A rebate — zero tax if taxable income ≤ ₹7,00,000
    if (taxableIncome <= 700000) {
      return {
        grossAnnual,
        taxableIncome,
        annualTax: 0,
        monthlyTDS: 0,
        baseTax: 0,
        cess: 0,
        rebate87A: taxableIncome > 300000, // 87A technically applies to 3L-7L range
        regime,
        note: taxableIncome <= 300000
          ? "No tax — income below basic exemption limit"
          : "No tax — Section 87A rebate applied (taxable income ≤ ₹7,00,000)",
      };
    }

    let tax = 0;

    // New Regime slabs — FY 2026-27 (Finance Act 2026)
    if (taxableIncome > 1500000) {
      tax += (taxableIncome - 1500000) * 0.30;
      tax += (1500000 - 1200000) * 0.20; // ₹60,000
      tax += (1200000 - 1000000) * 0.15; // ₹30,000
      tax += (1000000 - 700000) * 0.10;  // ₹30,000
      tax += (700000 - 300000) * 0.05;   // ₹20,000
    } else if (taxableIncome > 1200000) {
      tax += (taxableIncome - 1200000) * 0.20;
      tax += (1200000 - 1000000) * 0.15;
      tax += (1000000 - 700000) * 0.10;
      tax += (700000 - 300000) * 0.05;
    } else if (taxableIncome > 1000000) {
      tax += (taxableIncome - 1000000) * 0.15;
      tax += (1000000 - 700000) * 0.10;
      tax += (700000 - 300000) * 0.05;
    } else if (taxableIncome > 700000) {
      tax += (taxableIncome - 700000) * 0.10;
      tax += (700000 - 300000) * 0.05;
    }

    const cess = Math.round(tax * 0.04);
    const totalAnnualTax = Math.round(tax + cess);
    const monthlyTDS = Math.round(totalAnnualTax / 12);

    return {
      grossAnnual,
      taxableIncome,
      baseTax: Math.round(tax),
      cess,
      annualTax: totalAnnualTax,
      monthlyTDS,
      rebate87A: false,
      regime,
      note: "YTD-aware TDS spreading is a planned enhancement; monthly TDS = annualTax / 12.",
    };
  }
}

export default new StatutoryRulesService();
